"""Consistency checks for recurring calendar components.

A calendar that parses without error may still contain a recurring series
that cannot be used: the master component and its exceptions can each look
valid on their own while disagreeing with each other. For example, a master
``VEVENT`` may use an all-day ``DATE`` ``DTSTART`` while one of its
exceptions uses a time-zoned ``DATE-TIME`` ``RECURRENCE-ID``.

The checks in this module are called explicitly; parsing stays lenient. They
collect *all* errors that can be determined statically -- the recurrence set
is never expanded, so an infinite series is safe to check -- and never modify
the input: dates are not rewritten, missing ``UID`` values are not invented,
and exceptions are not removed. Whether a ``RECURRENCE-ID`` actually refers
to an instance generated by the master is intentionally out of scope.
"""

from __future__ import annotations

from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path
from typing import TYPE_CHECKING, Final

from icalendar.parser.content_line import Contentline
from icalendar.parser.ical.calendar import CalendarIcalParser
from icalendar.prop import vBroken
from icalendar.timezone import tzid_from_dt

if TYPE_CHECKING:
    from collections.abc import Sequence

    from icalendar.cal import Calendar, Component
    from icalendar.parser.parameter import Parameters


class SeriesErrorCode:
    """Stable error codes reported by the series consistency check.

    The string values are part of the public API and must not be renamed.
    """

    PARSE_ERROR: Final = "PARSE_ERROR"
    """A property or content line in the input could not be parsed."""

    MASTER_NOT_UNIQUE: Final = "MASTER_NOT_UNIQUE"
    """More than one component without ``RECURRENCE-ID`` shares a ``UID``."""

    DUPLICATE_RECURRENCE_ID: Final = "DUPLICATE_RECURRENCE_ID"
    """Two exceptions of the same series claim the same ``RECURRENCE-ID``."""

    RECURRENCE_ID_VALUE_TYPE_MISMATCH: Final = (
        "RECURRENCE_ID_VALUE_TYPE_MISMATCH"
    )
    """The ``RECURRENCE-ID`` value type (``DATE``/``DATE-TIME``) disagrees
    with the master ``DTSTART``."""

    RECURRENCE_ID_TIME_FORM_MISMATCH: Final = (
        "RECURRENCE_ID_TIME_FORM_MISMATCH"
    )
    """The ``RECURRENCE-ID`` time form (UTC, time-zoned, floating) disagrees
    with the master ``DTSTART``."""

    RRULE_COUNT_AND_UNTIL: Final = "RRULE_COUNT_AND_UNTIL"
    """An ``RRULE`` contains both ``COUNT`` and ``UNTIL``."""

    RRULE_UNTIL_VALUE_TYPE_MISMATCH: Final = (
        "RRULE_UNTIL_VALUE_TYPE_MISMATCH"
    )
    """The ``RRULE`` ``UNTIL`` value type does not match ``DTSTART``."""

    RRULE_UNTIL_TIME_FORM_MISMATCH: Final = "RRULE_UNTIL_TIME_FORM_MISMATCH"
    """The ``RRULE`` ``UNTIL`` time form does not match ``DTSTART`` (for
    example, a local ``UNTIL`` paired with a UTC ``DTSTART``)."""

    END_AND_DURATION: Final = "END_AND_DURATION"
    """The end property (``DTEND``/``DUE``) and ``DURATION`` are both present.
    """

    END_VALUE_TYPE_MISMATCH: Final = "END_VALUE_TYPE_MISMATCH"
    """The end property (``DTEND``/``DUE``) does not match ``DTSTART``."""

    NEGATIVE_DURATION: Final = "NEGATIVE_DURATION"
    """The ``DURATION`` is negative."""

    DURATION_VALUE_TYPE_MISMATCH: Final = "DURATION_VALUE_TYPE_MISMATCH"
    """An all-day component uses a duration with an hours/minutes/seconds
    part."""

    END_BEFORE_START: Final = "END_BEFORE_START"
    """The end property (``DTEND``/``DUE``) is earlier than ``DTSTART``."""

    RDATE_VALUE_TYPE_MISMATCH: Final = "RDATE_VALUE_TYPE_MISMATCH"
    """An ``RDATE`` value is incompatible with the series ``DTSTART``."""

    EXDATE_VALUE_TYPE_MISMATCH: Final = "EXDATE_VALUE_TYPE_MISMATCH"
    """An ``EXDATE`` value is incompatible with the series ``DTSTART``."""

    THISANDFUTURE_CONFLICT: Final = "THISANDFUTURE_CONFLICT"
    """Two ``RANGE=THISANDFUTURE`` exceptions claim overlapping original
    instances, or one such exception targets the original instance that
    another one starts at."""


@dataclass(frozen=True)
class SeriesConsistencyError:
    """A single consistency problem found in a recurring series.

    Attributes:
        code: Stable error code, see :class:`SeriesErrorCode`.
        uid: The ``UID`` of the affected series, or ``None`` when the
            component has no ``UID`` that could be determined.
        component_index: Index of the component within the checked calendar,
            counting only ``VEVENT``, ``VTODO`` and ``VJOURNAL`` components
            in document order, starting at 0. The index is independent of
            which other components are erroneous.
        property_path: Location of the offending property inside the
            component, e.g. ``["RRULE", 0, "UNTIL"]``. It is ``[]`` for a
            whole-component problem.
        message: Human-readable description of the problem.
        other_component_index: Index of the other component involved in a
            cross-component conflict (a duplicate master, a duplicate
            ``RECURRENCE-ID``, or a ``THISANDFUTURE`` overlap).
    """

    code: str
    uid: str | None
    component_index: int | None
    property_path: tuple[str | int, ...]
    message: str
    other_component_index: int | None = None

    @property
    def path(self) -> str:
        """Render :attr:`property_path` as an iCalendar-like dotted path."""
        parts: list[str] = []
        for part in self.property_path:
            if isinstance(part, int):
                parts[-1] = f"{parts[-1]}[{part}]"
            else:
                parts.append(part)
        return ".".join(parts)

    def __str__(self) -> str:
        location = []
        if self.uid is not None:
            location.append(f"uid={self.uid!r}")
        if self.component_index is not None:
            location.append(f"component[{self.component_index}]")
        if self.path:
            location.append(self.path)
        prefix = " ".join(location)
        if prefix:
            return f"{self.code} {prefix}: {self.message}"
        return f"{self.code}: {self.message}"


@dataclass(frozen=True)
class SeriesConsistencyReport:
    """Result of a series consistency check.

    Attributes:
        errors: All errors that could be determined, in a stable order.
    """

    errors: tuple[SeriesConsistencyError, ...]

    @property
    def ok(self) -> bool:
        """Whether no errors were found."""
        return not self.errors

    def codes(self) -> list[str]:
        """Return the error codes in report order."""
        return [error.code for error in self.errors]

    def for_uid(self, uid: str) -> tuple[SeriesConsistencyError, ...]:
        """Return all errors belonging to the series with the given ``UID``."""
        return tuple(error for error in self.errors if error.uid == uid)

    def raise_if_errors(self) -> None:
        """Raise :exc:`SeriesConsistencyErrorFound` if there are any errors."""
        if self.errors:
            raise SeriesConsistencyErrorFound(self)

    def __iter__(self):
        return iter(self.errors)

    def __len__(self) -> int:
        return len(self.errors)


class SeriesConsistencyErrorFound(Exception):
    """Raised when a checked calendar contains series consistency errors."""

    def __init__(self, report: SeriesConsistencyReport) -> None:
        self.report = report
        super().__init__(
            f"{len(report)} recurring series consistency error(s) found:\n"
            + "\n".join(f"- {error}" for error in report.errors)
        )

    def __len__(self) -> int:
        return len(self.report)


#: Component types that may take part in a recurring series.
RECURRING_COMPONENT_NAMES = ("VEVENT", "VTODO", "VJOURNAL")

#: ``DATE`` values; ``("DATETIME", None)`` floating; ``("DATETIME", tzid)``
#: a time-zoned (or UTC) value. Two values of the same form are directly
#: comparable.
TemporalForm = tuple[str, str | None]


def _temporal_value(value: object) -> date | datetime | timedelta | None:
    """Extract the native value stored behind a property wrapper."""
    if value is None:
        return None
    if isinstance(value, vBroken):
        return None
    dt = getattr(value, "dt", value)
    if isinstance(dt, (datetime, date, timedelta)):
        return dt
    return None


def _temporal_form(value: date | datetime) -> TemporalForm | None:
    """Classify a date value by value type and time form."""
    if isinstance(value, datetime):
        return "DATETIME", tzid_from_dt(value)
    if isinstance(value, date):
        return "DATE", None
    return None


def _period_end(value: object) -> date | datetime | None:
    """Return the start of an RDATE period (or the bare date)."""
    if isinstance(value, tuple) and value:
        value = value[0]
    return value if isinstance(value, (datetime, date)) else None


def _as_list(value: object) -> list:
    """Normalize a component property value into its list of occurrences."""
    if value is None:
        return []
    return value if isinstance(value, list) else [value]


def _occurrences(property_value: object) -> Iterable[tuple[int, object]]:
    """Yield ``(occurrence_index, value)`` pairs for one property.

    A repeated property line becomes a list at component level. An
    ``RDATE``/``EXDATE`` line may itself wrap several comma-separated dates in
    a ``vDDDLists`` object.
    """
    for occurrence_index, occurrence in enumerate(_as_list(property_value)):
        if isinstance(occurrence, vBroken):
            # Reported separately as PARSE_ERROR; nothing else to compare.
            continue
        dts = getattr(occurrence, "dts", None)
        if dts is not None:
            for value in dts:
                yield occurrence_index, value
        else:
            yield occurrence_index, occurrence


@dataclass(frozen=True)
class _Entry:
    """One recurring component and its stable document-order index."""

    index: int
    component: Component
    uid: str | None
    is_exception: bool


class _SeriesChecker:
    """Runs every check once and collects all resulting errors."""

    def __init__(self, calendar: Calendar) -> None:
        self.calendar = calendar
        self.errors: list[SeriesConsistencyError] = []
        self.entries: list[_Entry] = []

    def _add(
        self,
        entry: _Entry | None,
        code: str,
        path: Sequence[str | int],
        message: str,
        *,
        other: _Entry | None = None,
        component_index: int | None = None,
    ) -> None:
        self.errors.append(
            SeriesConsistencyError(
                code=code,
                uid=entry.uid if entry is not None else None,
                component_index=(
                    entry.index
                    if entry is not None
                    else component_index
                ),
                property_path=tuple(path),
                message=message,
                other_component_index=other.index if other is not None else None,
            )
        )

    def run(self) -> SeriesConsistencyReport:
        """Check the whole calendar and return every error found."""
        self._collect_entries()
        self._check_parse_errors()
        for entry in self.entries:
            self._check_component(entry)
        for group in self._groups():
            self._check_group(group)
        return SeriesConsistencyReport(tuple(self.errors))

    def _collect_entries(self) -> None:
        """Index recurring components in document order."""
        for component in self.calendar.walk():
            if component.name not in RECURRING_COMPONENT_NAMES:
                continue
            raw_uid = component.get("UID")
            uid = str(raw_uid) if raw_uid is not None else None
            recurrence_id = component.get("RECURRENCE-ID")
            is_exception = recurrence_id is not None
            self.entries.append(
                _Entry(
                    index=len(self.entries),
                    component=component,
                    uid=uid,
                    is_exception=is_exception,
                )
            )

    def _check_parse_errors(self) -> None:
        """Turn the parser's recorded property/line errors into report items."""
        # Parse errors of the calendar itself (e.g. a malformed content line
        # that belongs to no component).
        for _name, message in self.calendar.errors:
            self.errors.append(
                SeriesConsistencyError(
                    code=SeriesErrorCode.PARSE_ERROR,
                    uid=None,
                    component_index=None,
                    property_path=(),
                    message=message,
                )
            )
        for entry in self.entries:
            self._check_component_parse_errors(entry)

    def _check_component_parse_errors(self, entry: _Entry) -> None:
        """Match recorded component errors to the broken property occurrence."""
        broken_by_name: dict[str, list[object]] = {}
        for name, value in entry.component.items():
            for occurrence in _as_list(value):
                if isinstance(occurrence, vBroken):
                    broken_by_name.setdefault(name, []).append(occurrence)
        used: dict[str, int] = {}
        for name, message in entry.component.errors:
            if name is not None and broken_by_name.get(name):
                occurrence = used.get(name, 0)
                used[name] = occurrence + 1
                path: tuple[str | int, ...] = (name,)
                if occurrence:
                    path = (name, occurrence)
            elif name is not None:
                path = (name,)
            else:
                path = ()
            self._add(entry, SeriesErrorCode.PARSE_ERROR, path, message)

    def _check_component(self, entry: _Entry) -> None:
        """Run all checks that concern one component in isolation."""
        start = _temporal_value(entry.component.get("DTSTART"))
        start_form = _temporal_form(start) if start is not None else None
        self._check_rrules(entry, start, start_form)
        self._check_end(entry, start, start_form)
        if start_form is not None:
            self._check_date_lists(entry, "RDATE", start_form)
            self._check_date_lists(entry, "EXDATE", start_form)

    def _check_rrules(
        self,
        entry: _Entry,
        start: date | datetime | timedelta | None,
        start_form: TemporalForm | None,
    ) -> None:
        """Check COUNT/UNTIL exclusivity and the UNTIL/``DTSTART`` relation."""
        start = start if isinstance(start, (datetime, date)) else None
        for occurrence, rrule in enumerate(_as_list(entry.component.get("RRULE"))):
            if isinstance(rrule, vBroken):
                continue
            has_count = "COUNT" in rrule
            has_until = "UNTIL" in rrule
            base_path = ("RRULE", occurrence) if occurrence else ("RRULE",)
            if has_count and has_until:
                self._add(
                    entry,
                    SeriesErrorCode.RRULE_COUNT_AND_UNTIL,
                    base_path,
                    "RRULE must not contain both COUNT and UNTIL.",
                )
            if not has_until:
                continue
            until = rrule["UNTIL"]
            until = until[0] if isinstance(until, list) else until
            until = _temporal_value(until)
            if not isinstance(until, (datetime, date)):
                continue
            until_form = _temporal_form(until)
            path = base_path + ("UNTIL",)
            if start_form is None:
                # Without a usable DTSTART the relation cannot be checked;
                # the parser already reported the broken/missing property.
                continue
            if isinstance(start, date) and not isinstance(start, datetime):
                if until_form[0] != "DATE":
                    self._add(
                        entry,
                        SeriesErrorCode.RRULE_UNTIL_VALUE_TYPE_MISMATCH,
                        path,
                        "UNTIL must be a DATE when DTSTART is a DATE.",
                    )
                continue
            if until_form[0] != "DATETIME":
                self._add(
                    entry,
                    SeriesErrorCode.RRULE_UNTIL_VALUE_TYPE_MISMATCH,
                    path,
                    "UNTIL must be a DATE-TIME when DTSTART is a DATE-TIME.",
                )
                continue
            if start_form[1] is None:
                # A floating DTSTART pairs with a floating or UTC UNTIL
                # (RFC 5545 3.3.10); both are usable.
                continue
            if until_form[1] != "UTC":
                self._add(
                    entry,
                    SeriesErrorCode.RRULE_UNTIL_TIME_FORM_MISMATCH,
                    path,
                    "UNTIL must be specified as a UTC DATE-TIME when DTSTART "
                    "has a time zone.",
                )

    def _check_end(
        self,
        entry: _Entry,
        start: date | datetime | timedelta | None,
        start_form: TemporalForm | None,
    ) -> None:
        """Check end property / DURATION exclusivity and value ranges."""
        component = entry.component
        end_name = "DUE" if component.name == "VTODO" else "DTEND"
        end_value = component.get(end_name)
        duration_value = component.get("DURATION")
        end = _temporal_value(end_value)
        duration = _temporal_value(duration_value)
        if end_value is not None and duration_value is not None:
            self._add(
                entry,
                SeriesErrorCode.END_AND_DURATION,
                ("DURATION",),
                f"{end_name} and DURATION must not both be present.",
            )
        if isinstance(duration, timedelta) and duration < timedelta(0):
            self._add(
                entry,
                SeriesErrorCode.NEGATIVE_DURATION,
                ("DURATION",),
                "DURATION must not be negative.",
            )
        if (
            start_form == ("DATE", None)
            and isinstance(duration, timedelta)
            and (duration.seconds or duration.microseconds)
        ):
            self._add(
                entry,
                SeriesErrorCode.DURATION_VALUE_TYPE_MISMATCH,
                ("DURATION",),
                "DURATION must be expressed in days or weeks when DTSTART "
                "is a DATE.",
            )
        if not isinstance(end, (datetime, date)) or not isinstance(
            start, (datetime, date)
        ):
            return
        end_form = _temporal_form(end)
        if end_form != start_form:
            self._add(
                entry,
                SeriesErrorCode.END_VALUE_TYPE_MISMATCH,
                (end_name,),
                f"{end_name} must use the same value type and time form "
                f"as DTSTART.",
            )
            # Comparing, e.g., a date with a datetime would add misleading
            # range errors, so stop here.
            return
        if end < start:
            self._add(
                entry,
                SeriesErrorCode.END_BEFORE_START,
                (end_name,),
                f"{end_name} must not be earlier than DTSTART.",
            )

    def _check_date_lists(
        self, entry: _Entry, name: str, start_form: TemporalForm
    ) -> None:
        """Check RDATE/EXDATE values against the series time type."""
        property_value = entry.component.get(name)
        for occurrence, value in _occurrences(property_value):
            if isinstance(value, vBroken):
                continue
            value = getattr(value, "dt", value)
            # RDATE periods are (start, end/duration); EXDATE carries only
            # dates, so a period there is itself a mismatch.
            is_period = isinstance(value, tuple)
            compared = _period_end(value) if is_period else value
            compared = compared if isinstance(compared, (datetime, date)) else None
            path = (name, occurrence) if occurrence else (name,)
            if not isinstance(compared, (datetime, date)):
                # An unparsable value was already reported as PARSE_ERROR.
                continue
            value_form = _temporal_form(compared)
            code = (
                SeriesErrorCode.RDATE_VALUE_TYPE_MISMATCH
                if name == "RDATE"
                else SeriesErrorCode.EXDATE_VALUE_TYPE_MISMATCH
            )
            if name == "EXDATE" and is_period:
                self._add(
                    entry,
                    code,
                    path,
                    "EXDATE values must be dates, not periods.",
                )
                continue
            if value_form[0] != start_form[0]:
                expected = "DATE" if start_form[0] == "DATE" else "DATE-TIME"
                self._add(
                    entry,
                    code,
                    path,
                    f"{name} values must use the {expected} value type of "
                    f"DTSTART.",
                )
                continue
            if start_form[0] == "DATETIME" and value_form[1] != start_form[1]:
                self._add(
                    entry,
                    code,
                    path,
                    f"{name} values must use the same time form (UTC, time "
                    f"zone, or floating) as DTSTART.",
                )

    def _groups(self) -> list[list[_Entry]]:
        """Group entries by UID, keeping document order."""
        groups: dict[str, list[_Entry]] = {}
        for entry in self.entries:
            if entry.uid is None:
                continue
            groups.setdefault(entry.uid, []).append(entry)
        return [
            sorted(group, key=lambda entry: entry.index)
            for group in sorted(
                groups.values(), key=lambda group: group[0].index
            )
        ]

    def _check_group(self, entries: list[_Entry]) -> None:
        """Check one series: a unique master and consistent exceptions."""
        masters = [entry for entry in entries if not entry.is_exception]
        exceptions = [entry for entry in entries if entry.is_exception]
        for duplicate_master in masters[1:]:
            self._add(
                duplicate_master,
                SeriesErrorCode.MASTER_NOT_UNIQUE,
                (),
                "Only one master component (without RECURRENCE-ID) is allowed "
                "per UID.",
                other=masters[0],
            )
        master = masters[0] if masters else None
        master_start = (
            _temporal_value(master.component.get("DTSTART")) if master else None
        )
        master_form = (
            _temporal_form(master_start)
            if isinstance(master_start, (datetime, date))
            else None
        )
        claimed: dict[
            tuple[TemporalForm, object], _Entry
        ] = {}
        this_and_future: list[tuple[_Entry, date | datetime, TemporalForm]] = []
        for entry in exceptions:
            identity = self._check_exception(entry, master_form)
            if identity is None:
                continue
            form, key = identity
            previous = claimed.get((form, key))
            if previous is not None:
                self._add(
                    entry,
                    SeriesErrorCode.DUPLICATE_RECURRENCE_ID,
                    ("RECURRENCE-ID",),
                    "Two exceptions claim the same RECURRENCE-ID; the modified "
                    "DTSTART of an exception does not change its identity.",
                    other=previous,
                )
            else:
                claimed[(form, key)] = entry
            range_param = entry.component["RECURRENCE-ID"].params.get("RANGE")
            if (
                range_param is not None
                and str(range_param).upper() == "THISANDFUTURE"
            ):
                this_and_future.append((entry, key, form))
        self._check_this_and_future(this_and_future)

    def _check_exception(
        self, entry: _Entry, master_form: TemporalForm | None
    ) -> tuple[TemporalForm, date | datetime] | None:
        """Check one exception's RECURRENCE-ID against its master."""
        recurrence_id = entry.component.get("RECURRENCE-ID")
        value = _temporal_value(recurrence_id)
        if not isinstance(value, (datetime, date)):
            # Broken RECURRENCE-ID: the parse error is reported separately.
            return None
        value_form = _temporal_form(value)
        if master_form is not None:
            if value_form[0] != master_form[0]:
                self._add(
                    entry,
                    SeriesErrorCode.RECURRENCE_ID_VALUE_TYPE_MISMATCH,
                    ("RECURRENCE-ID",),
                    "RECURRENCE-ID must use the same value type (DATE or "
                    "DATE-TIME) as the master DTSTART.",
                )
            elif (
                master_form[0] == "DATETIME"
                and value_form[1] != master_form[1]
            ):
                self._add(
                    entry,
                    SeriesErrorCode.RECURRENCE_ID_TIME_FORM_MISMATCH,
                    ("RECURRENCE-ID",),
                    "RECURRENCE-ID must use the same time form (UTC, time "
                    "zone, or floating) as the master DTSTART.",
                )
        return value_form, value

    def _check_this_and_future(
        self,
        claims: list[tuple[_Entry, date | datetime, TemporalForm]],
    ) -> None:
        """Find overlapping RANGE=THISANDFUTURE exception claims.

        Only the original instance named by RECURRENCE-ID is used. A
        THISANDFUTURE exception starting at an earlier instance claims the
        instance named by a later one, which is a conflicting declaration.
        """
        claims = sorted(claims, key=lambda item: item[0].index)
        for position, (entry, start, form) in enumerate(claims):
            for other_entry, other_start, other_form in claims[position + 1 :]:
                if other_form != form:
                    continue
                if other_start < start:
                    continue
                # Equal original instances are DUPLICATE_RECURRENCE_ID, also
                # reported above; every later instance lies in this range.
                if other_start == start:
                    continue
                self._add(
                    entry,
                    SeriesErrorCode.THISANDFUTURE_CONFLICT,
                    ("RECURRENCE-ID",),
                    "This RANGE=THISANDFUTURE exception also claims the "
                    "original instance of another THISANDFUTURE exception.",
                    other=other_entry,
                )


class _LenientCalendarParser(CalendarIcalParser):
    """Parse raw input leniently for the consistency checker.

    All components keep their unparsable properties as broken values instead
    of aborting the whole parse, so the checker can report the parse error and
    continue with the remaining components. This parser is local to the
    checker; :meth:`Calendar.from_ical <icalendar.Calendar.from_ical>` keeps
    its existing (per-component) leniency.
    """

    def handle_line_parse_error(self, exception: Exception) -> None:
        component = self.component
        if component is None:
            raise exception
        component.errors.append((None, str(exception)))

    def handle_property_parse_error(
        self,
        exception: Exception,
        name: str,
        params: Parameters,
        val: str,
        line: Contentline,
    ) -> None:
        factory = self.get_factory_for_property(name, params)
        expected_type = getattr(factory, "__name__", "unknown")
        broken = vBroken.from_parse_error(
            raw_value=val,
            params=params,
            property_name=name,
            expected_type=expected_type,
            error=exception,
        )
        self.component.errors.append((name, str(exception)))
        self.component.add(name, broken, encode=0)


def check_series_consistency(
    calendar_or_ical: Calendar | str | bytes | Path,
) -> SeriesConsistencyReport:
    """Check the consistency of recurring series in a calendar.

    Components are collected per ``UID`` into a master (the component without
    ``RECURRENCE-ID``) and its exceptions. The check verifies that the master
    is unique, exception identities are not duplicated, the
    ``RECURRENCE-ID`` value type and time form match the master ``DTSTART``,
    ``RRULE`` ``COUNT``/``UNTIL`` exclusivity and the ``UNTIL``/``DTSTART``
    type requirements, ``DTEND``/``DURATION`` (or ``DUE``/``DURATION``)
    exclusivity and value ranges, ``RDATE``/``EXDATE`` time-type
    compatibility, and conflicting ``RANGE=THISANDFUTURE`` declarations.

    Parameters:
        calendar_or_ical: An already parsed
            :class:`~icalendar.Calendar`, or raw iCalendar data (``str``,
            ``bytes`` or a :class:`~pathlib.Path`). Raw data is parsed
            leniently for the check only; existing parse errors are included
            in the report instead of aborting it.

    Returns:
        A :class:`SeriesConsistencyReport` containing every error that could
        be determined. The report is empty (``report.ok is True``) when the
        calendar is consistent. The check never expands a recurrence set,
        rewrites dates, invents ``UID`` values, or deletes exceptions.

    Example:
        .. code-block:: pycon

            >>> from icalendar import check_series_consistency, Calendar
            >>> report = check_series_consistency(Calendar.example())
            >>> report.ok
            True
    """
    from icalendar.cal.calendar import Calendar

    if isinstance(calendar_or_ical, (str, bytes, Path)):
        data = (
            calendar_or_ical.read_bytes()
            if isinstance(calendar_or_ical, Path)
            else calendar_or_ical
        )
        parser = _LenientCalendarParser(
            data, Calendar._get_component_factory(), Calendar.types_factory
        )
        calendars = parser.parse()
        reports = []
        for parsed_calendar in calendars:
            reports.append(_SeriesChecker(parsed_calendar).run())
        if len(calendars) == 1:
            return reports[0]
        # Multiple top-level calendars: merge the reports, keeping the order
        # of calendar documents and components.
        merged: list[SeriesConsistencyError] = []
        for report in reports:
            merged.extend(report.errors)
        return SeriesConsistencyReport(tuple(merged))
    calendar = calendar_or_ical
    return _SeriesChecker(calendar).run()


