"""Iterate the instances of recurring events within a time window.

This module expands the recurrence set of the ``VEVENT`` components of a
calendar following :rfc:`5545#section-3.8.5`:

1.  The occurrences generated by ``DTSTART``, ``RRULE``, and
    ``RDATE`` are merged and duplicates are removed.
2.  The occurrences listed in ``EXDATE`` are excluded.
3.  Exception components with a matching ``RECURRENCE-ID`` relocate
    (moved) or remove (cancelled) single instances.

The result is a read-only, lazy :class:`InstanceIterator`. Each yielded
:class:`Instance` carries the identity of the original occurrence, the
actual start, and the source that generated the occurrence.

All window arithmetic is performed in a timezone that the caller must
provide explicitly; the process timezone is never consulted.

Example:
    .. code-block:: pycon

        >>> from datetime import datetime, timezone
        >>> from icalendar import Calendar, Event
        >>> from icalendar.recurrence import iter_instances
        >>> event = Event()
        >>> event.add(
        ...     "DTSTART", datetime(2024, 1, 31, 9, 0, tzinfo=timezone.utc)
        ... )
        >>> event.add("RRULE", {"FREQ": ["MONTHLY"], "COUNT": [3]})
        >>> calendar = Calendar()
        >>> calendar.add_component(event)
        >>> for instance in iter_instances(
        ...     calendar, "2024-01-01", "2025-01-01", tz="UTC"
        ... ):
        ...     print(instance.identity, instance.source)
        2024-01-31 09:00:00+00:00 DTSTART
        2024-03-31 09:00:00+00:00 RRULE
        2024-05-31 09:00:00+00:00 RRULE
"""

